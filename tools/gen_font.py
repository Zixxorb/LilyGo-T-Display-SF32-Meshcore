#!/usr/bin/env python3
"""Generates src/platform/SF32Font.h: anti-aliased glyphs for SF32Display.

MeshCore's UIs are laid out in 128x64 "OLED pixels" with the classic 6x8 GFX font
(text size n = a 6n x 8n cell). SF32Display maps that layout onto the 480x480
panel at SCALE physical pixels per logical pixel, and draws text with these glyphs
at full panel resolution instead of scaling the 5x7 bitmap font.

One glyph set per text size in SIZES. 4 bits of coverage per pixel.
The font is proportional: each glyph has its own advance, and SF32Display reports
real text widths (in logical pixels) to MeshCore's layout code.

usage: python3 tools/gen_font.py [FONT.ttf]   (needs Pillow; run with the system python)
The T-Deck's font: SCALE=1.875 OUT=src/tdeck/TDeckFont.h python3 tools/gen_font.py
Default font: Noto Sans Medium (SIL Open Font License 1.1).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SCALE = float(os.environ.get("SCALE", "3.5"))  # must match SF32Display::SCALE
# text size -> characters (None = all printable ASCII), or (characters, scale) for a set drawn
# at another scale than its number. Size 5 is the clock's digits; "size" 9 is the clock
# page's battery % at 1.5x (SF32Display::TEXT_BATTERY), between sizes 1 and 2.
SIZES = {1: None, 2: None, 3: None, 5: "0123456789:- ", 9: ("0123456789%- ", 1.5)}
FIRST, LAST = 32, 126
FONT = "/usr/share/fonts/noto/NotoSans-Medium.ttf"
OUT = os.environ.get("OUT") or os.path.join(os.path.dirname(__file__), "..", "src", "platform", "SF32Font.h")

# Cap height as a fraction of the 8n-pixel cell (the 5x7 font's caps fill 7 of 8 rows,
# but MeshCore lines are often only 10-11 px apart, so leave room for descenders).
CAP_FRACTION = 0.70


def render_size(font_path, n, charset):
    cell_w, cell_h = 6 * n * SCALE, 8 * n * SCALE
    # Pick the pixel size whose cap height matches the target.
    target_cap = CAP_FRACTION * cell_h
    px = int(target_cap / 0.714)
    font = ImageFont.truetype(font_path, px)
    cap_top = font.getbbox("H")[1]
    cap_h = font.getbbox("H")[3] - cap_top
    # Baseline so that caps are centred in the upper 7/8 of the cell.
    top_pad = (cell_h * 0.875 - cap_h) / 2
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        if charset is not None and ch not in charset:
            glyphs.append((0, 0, 0, 0, 0, b""))
            continue
        x0 = 0
        y0 = top_pad - cap_top
        advance = font.getlength(ch)
        # render on a canvas big enough for overhangs, then crop to the ink
        pad = int(px)
        img = Image.new("L", (int(cell_w) + 2 * pad, int(cell_h) + 2 * pad), 0)
        ImageDraw.Draw(img).text((pad + x0, pad + y0), ch, font=font, fill=255)
        bbox = img.getbbox()
        if not bbox:
            glyphs.append((0, 0, 0, 0, round(advance * 16), b""))
            continue
        crop = img.crop(bbox)
        w, h = crop.size
        data = bytearray()
        pix = crop.tobytes()
        for y in range(h):
            row = [(pix[y * w + x] + 8) // 17 for x in range(w)]  # 0..15
            if w % 2:
                row.append(0)
            for x in range(0, len(row), 2):
                data.append((row[x] << 4) | row[x + 1])
        glyphs.append((bbox[0] - pad, bbox[1] - pad, w, h, round(advance * 16), bytes(data)))
    return glyphs, px


def main():
    font_path = sys.argv[1] if len(sys.argv) > 1 else FONT
    out = []
    out.append("// Generated by tools/gen_font.py from %s. Do not edit.\n" % os.path.basename(font_path))
    out.append("// Font: SIL Open Font License 1.1 (Noto fonts, Google).\n")
    out.append("#pragma once\n#include <stdint.h>\n\n")
    out.append("struct SF32Glyph {\n  int8_t x, y;   // ink offset from the pen position / cell top (physical px)\n"
               "  uint8_t w, h;  // ink size\n  uint16_t adv;  // advance, 1/16 px\n  uint32_t data; // offset into the size's bitmap (4bpp, rows padded to bytes)\n};\n\n")
    out.append("#define SF32_FONT_FIRST %d\n#define SF32_FONT_LAST %d\n#define SF32_FONT_SIZES %d\n\n" % (FIRST, LAST, len(SIZES)))
    for n, charset in SIZES.items():
        scale = n
        if isinstance(charset, tuple):
            charset, scale = charset
        glyphs, px = render_size(font_path, scale, charset)
        blob = bytearray()
        out.append("// text size %d: %d px font\n" % (n, px))
        out.append("static const SF32Glyph sf32_glyphs_%d[] = {\n" % n)
        for (x, y, w, h, adv, data) in glyphs:
            out.append("  {%d, %d, %d, %d, %d, %d},\n" % (x, y, w, h, adv, len(blob)))
            blob += data
        out.append("};\n")
        out.append("static const uint8_t sf32_bitmap_%d[%d] = {\n" % (n, max(1, len(blob))))
        for i in range(0, len(blob), 24):
            out.append("  " + ",".join("0x%02X" % b for b in blob[i:i + 24]) + ",\n")
        out.append("};\n\n")
    out.append("static const uint8_t sf32_font_text_size[SF32_FONT_SIZES] = {%s};\n"
               % ", ".join(str(n) for n in SIZES))
    out.append("static const SF32Glyph* const sf32_glyphs[SF32_FONT_SIZES] = {%s};\n"
               % ", ".join("sf32_glyphs_%d" % n for n in SIZES))
    out.append("static const uint8_t* const sf32_bitmaps[SF32_FONT_SIZES] = {%s};\n"
               % ", ".join("sf32_bitmap_%d" % n for n in SIZES))
    with open(OUT, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
