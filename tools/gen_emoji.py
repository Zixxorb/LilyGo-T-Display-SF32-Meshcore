#!/usr/bin/env python3
# Builds src/platform/SF32Emoji.h: the ~100 most used emoji (plus a few mesh ones) as small
# colour pictures, RGB565 + alpha, sized for text size 1 (bigger text scales them up).
# From Google's Noto emoji PNGs (github.com/googlefonts/noto-emoji, 2D/png/128). Its README
# puts image resources under Apache 2.0; its LICENSE file (licenses/Noto-Emoji-LICENSE.txt)
# is the SIL OFL 1.1. Either allows this.
#
# SF32Display::translateUTF8ToBlocks turns each into two bytes, 0xF8 + (i >> 6) then
# 0x80 + (i & 63): bytes that never occur in UTF-8 text, so translated text stays as it is
# when it's translated again. Others show as the placeholder block.
#
# Usage: python3 tools/gen_emoji.py DIR_WITH_emoji_uXXXX.png   (keep the order: add at the end)
# Another scale (the T-Deck): SCALE=1.875 OUT=src/tdeck/TDeckEmoji.h python3 tools/gen_emoji.py
#   DIR; or, without the PNGs, shrink the SF32's set: ... gen_emoji.py src/platform/SF32Emoji.h
import os, re, sys
from PIL import Image

EMOJI = [  # most used first (Unicode's emoji frequency list), then mesh and status ones
    "1f602", "2764", "1f923", "1f44d", "1f62d", "1f64f", "1f618", "1f970", "1f60d", "1f60a",
    "1f389", "1f601", "1f495", "1f97a", "1f605", "1f525", "263a", "1f926", "2665", "1f937",
    "1f644", "1f606", "1f917", "1f609", "1f382", "1f914", "1f44f", "1f642", "1f633", "1f973",
    "1f60e", "1f44c", "1f49c", "1f614", "1f4aa", "2728", "1f496", "1f440", "1f60b", "1f60f",
    "1f622", "1f449", "1f497", "1f629", "1f4af", "1f339", "1f49e", "1f388", "1f499", "1f603",
    "1f621", "1f490", "1f61c", "1f648", "1f91e", "1f604", "1f924", "1f64c", "1f92a", "2763",
    "1f600", "1f48b", "1f480", "1f447", "1f494", "1f60c", "1f493", "1f929", "1f643", "1f62c",
    "1f631", "1f634", "1f92d", "1f610", "1f31e", "1f612", "1f607", "1f338", "1f608", "1f3b6",
    "270c", "1f38a", "1f975", "1f61e", "1f49a", "2600", "1f5a4", "1f4b0", "1f61a", "1f451",
    "1f381", "1f4a5", "1f64b", "2639", "1f611", "1f974", "1f448", "1f4a9", "2705", "1f44b",
    "1f44e", "274c", "26a0", "2757", "2753", "2b50", "1f4e1", "1f4f6", "1f50b", "26a1",
    "1f4cd", "1f3f7", "1f916", "1f319", "1f327", "1f3e0", "1f697", "1f6f0",
]
SCALE = float(os.environ.get("SCALE", "3.5"))  # SF32Display::SCALE
PX = round(7 * SCALE)  # text size 1: 7 logical px
OUT = os.environ.get("OUT", "src/platform/SF32Emoji.h")

def pictures(src):
    """(code point, RGBA image) for each of EMOJI: from Noto's PNGs, or from an SF32Emoji.h"""
    if not src.endswith(".h"):
        for e in EMOJI:
            yield e, Image.open(os.path.join(src, f"emoji_u{e}.png")).convert("RGBA")
        return
    text = open(src).read()
    n = int(re.search(r"SF32_EMOJI_PX (\d+)", text).group(1))
    cps = re.search(r"sf32_emoji_cp\[[^]]*\] = \{(.*?)\};", text, re.S).group(1)
    cps = [c.strip()[2:] for c in cps.split(",") if c.strip()]
    rgb = [int(v, 16) for v in re.search(r"sf32_emoji_rgb\[\] = \{(.*?)\};", text, re.S).group(1).replace(",", " ").split()]
    alpha = [int(v) for v in re.search(r"sf32_emoji_a\[\] = \{(.*?)\};", text, re.S).group(1).replace(",", " ").split()]
    for k, e in enumerate(EMOJI):
        i = cps.index(e) * n * n
        im = Image.new("RGBA", (n, n))
        im.putdata([(((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31, a)
                    for v, a in zip(rgb[i:i + n * n], alpha[i:i + n * n])])
        yield e, im

def main():
    src = sys.argv[1]
    assert len(EMOJI) <= 128 and len(set(EMOJI)) == len(EMOJI)
    rgb, alpha = [], []
    for e, im in pictures(src):
        im = im.resize((PX, PX), Image.LANCZOS)
        for r, g, b, a in im.getdata():
            rgb.append((((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)) if a else 0)
            alpha.append(a)
    out = ["// Generated by tools/gen_emoji.py from Noto emoji PNGs (see THIRD_PARTY.md). Do not edit.",
           "#pragma once", "#include <stdint.h>", "",
           f"#define SF32_EMOJI_N  {len(EMOJI)}",
           f"#define SF32_EMOJI_PX {PX}",
           "static const uint32_t sf32_emoji_cp[SF32_EMOJI_N] = {"]
    out += ["  " + ", ".join("0x" + e for e in EMOJI[i:i + 10]) + "," for i in range(0, len(EMOJI), 10)]
    out += ["};", "static const uint16_t sf32_emoji_rgb[] = {"]
    out += ["  " + ",".join(f"0x{v:04x}" for v in rgb[i:i + 24]) + "," for i in range(0, len(rgb), 24)]
    out += ["};", "static const uint8_t sf32_emoji_a[] = {"]
    out += ["  " + ",".join(str(v) for v in alpha[i:i + 32]) + "," for i in range(0, len(alpha), 32)]
    out += ["};"]
    open(OUT, "w").write("\n".join(out) + "\n")
    print(len(EMOJI), "emoji,", PX, "px,", len(rgb) * 3 // 1024, "KB")

main()
