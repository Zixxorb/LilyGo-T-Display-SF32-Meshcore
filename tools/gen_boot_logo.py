#!/usr/bin/env python3
# Builds src/platform/SF32Logo.h: the boot screen's logo (the mark over the VESPER wordmark,
# dark-background colours) as RGB565 + alpha at the panel's own resolution, from the README
# banner docs/images/logo-dark.svg (tools/gen_logo.py; lettering already outlines).
# Needs rsvg-convert (librsvg) and Pillow.
# Usage: python3 tools/gen_boot_logo.py [width_px]   (default 280 panel px = 80 logical)
# The T-Deck's: OUT=src/tdeck/TDeckLogo.h python3 tools/gen_boot_logo.py 150   (80 logical at 1.875)
import io, os, re, subprocess, sys
from PIL import Image

W_PX = int(sys.argv[1]) if len(sys.argv) > 1 else 280
svg = open("docs/images/logo-dark.svg").read()
mark = re.search(r'(<g transform="scale\(0\.7\)">.*?</g>)', svg, re.S).group(1)
word = re.search(r'<path d="([^"]+)" fill="(#E6EDF3)"/>', svg)
# the wordmark spans x 195..483, y 55..85 in the banner; the mark is 168 x 140
VW, GAP = 300, 22
stacked = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VW} {140 + GAP + 32}">'
           f'<g transform="translate({(VW - 168) / 2} 0)">{mark}</g>'
           f'<g transform="translate({(VW - 288) / 2 - 195} {140 + GAP - 55})"><path d="{word.group(1)}" fill="{word.group(2)}"/></g></svg>')
png = subprocess.run(["rsvg-convert", "-w", str(W_PX), "-f", "png"], input=stacked.encode(), capture_output=True, check=True).stdout
im = Image.open(io.BytesIO(png)).convert("RGBA")
w, h = im.size
bbox = im.getbbox()  # trim empty rows / columns
im = im.crop(bbox); w, h = im.size
rgb, alpha = [], []
px = im.tobytes()
for i in range(0, len(px), 4):
    r, g, b, a = px[i:i + 4]
    rgb.append((((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)) if a else 0)
    alpha.append(a)
with open(os.environ.get("OUT", "src/platform/SF32Logo.h"), "w") as f:
    f.write("// Generated by tools/gen_boot_logo.py from docs/images/logo-dark.svg: don't edit.\n")
    f.write("// The boot screen's Vesper logo, RGB565 + alpha, in panel pixels.\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define SF32_LOGO_W {w}\n#define SF32_LOGO_H {h}\n")
    f.write("static const uint16_t sf32_logo_rgb[] = {\n")
    for i in range(0, len(rgb), 16): f.write("  " + ",".join(f"0x{v:04x}" for v in rgb[i:i + 16]) + ",\n")
    f.write("};\nstatic const uint8_t sf32_logo_a[] = {\n")
    for i in range(0, len(alpha), 32): f.write("  " + ",".join(str(v) for v in alpha[i:i + 32]) + ",\n")
    f.write("};\n")
im.save("/tmp/claude-1000/-home-carter-Desktop-Meshcore-Porting/6931b8cb-30d4-4837-b8d5-03775d0f4079/scratchpad/boot_logo.png")
print(w, h, w * h * 3, "bytes")
